CREATE SCHEMA IF NOT EXISTS nimbus;

DROP TABLE IF EXISTS nimbus.RENEW_LOG CASCADE;
DROP TABLE IF EXISTS nimbus.PYMT_TXN CASCADE;
DROP TABLE IF EXISTS nimbus.BILL_DTL CASCADE;
DROP TABLE IF EXISTS nimbus.BILL_HDR CASCADE;
DROP TABLE IF EXISTS nimbus.RTD_EVT CASCADE;
DROP TABLE IF EXISTS nimbus.USG_CDR CASCADE;
DROP TABLE IF EXISTS nimbus.SUBSCR_DISC CASCADE;
DROP TABLE IF EXISTS nimbus.SUBSCR_MSTR CASCADE;
DROP TABLE IF EXISTS nimbus.CONTRACT_TERMS CASCADE;
DROP TABLE IF EXISTS nimbus.DISC_CFG CASCADE;
DROP TABLE IF EXISTS nimbus.TRF_RATE_CFG CASCADE;
DROP TABLE IF EXISTS nimbus.RT_PLAN_CFG CASCADE;
DROP TABLE IF EXISTS nimbus.CUST_MSTR CASCADE;

CREATE TABLE nimbus.CUST_MSTR (
    CUST_NO      VARCHAR PRIMARY KEY,
    CUST_NM      VARCHAR,
    CUST_TYP     CHAR(1)      CHECK (CUST_TYP IN ('R','B')),
    CRT_DT       DATE,
    STAT_CD      CHAR(1)
);

CREATE TABLE nimbus.RT_PLAN_CFG (
    PLN_CD           VARCHAR PRIMARY KEY,
    PLN_DESC         VARCHAR,
    MTHLY_FEE        NUMERIC(12,2),
    INCL_DATA_MB     INTEGER,
    OVG_RT_PER_MB    NUMERIC(12,4),
    INCL_VOICE_MIN   INTEGER,
    VOICE_RT_PER_MIN NUMERIC(12,4),
    EFF_FROM         DATE,
    EFF_TO           DATE NULL
);

CREATE TABLE nimbus.TRF_RATE_CFG (
    RATE_ID   BIGINT PRIMARY KEY,
    PLN_CD    VARCHAR,
    USG_TYP   VARCHAR CHECK (USG_TYP IN ('DATA','VOICE','SMS')),
    UNIT_RT   NUMERIC(12,4),
    EFF_FROM  DATE,
    EFF_TO    DATE NULL
    -- FOREIGN KEY (PLN_CD) removed
);

CREATE TABLE nimbus.DISC_CFG (
    DISC_CD    VARCHAR PRIMARY KEY,
    DISC_DESC  VARCHAR,
    DISC_PCT   NUMERIC(5,2),
    VALID_FROM DATE,
    VALID_TO   DATE
);

CREATE TABLE nimbus.CONTRACT_TERMS (
    CNTR_ID          BIGINT PRIMARY KEY,
    CUST_NO          VARCHAR,
    PLN_CD           VARCHAR,
    AGREED_MTHLY_FEE NUMERIC(12,2),
    DISC_CD          VARCHAR NULL,
    START_DT         DATE,
    END_DT           DATE,
    AUTO_RENEW_FLG   CHAR(1) CHECK (AUTO_RENEW_FLG IN ('Y','N'))
    -- FOREIGN KEY constraints removed
);

CREATE TABLE nimbus.SUBSCR_MSTR (
    SUBSCR_ID     VARCHAR PRIMARY KEY,
    CUST_NO       VARCHAR,
    MSISDN        VARCHAR,
    PLN_CD        VARCHAR,
    ACT_DT        DATE,
    DEACT_DT      DATE NULL,
    PROV_STAT     VARCHAR CHECK (PROV_STAT IN ('ACTIVE','SUSP','TERM')),
    BILL_ACCT_NO VARCHAR NULL
    -- FOREIGN KEY constraints removed
);

CREATE TABLE nimbus.SUBSCR_DISC (
    SUBSCR_ID   VARCHAR,
    DISC_CD     VARCHAR,
    APPLIED_FROM DATE,
    APPLIED_TO   DATE NULL,
    PRIMARY KEY (SUBSCR_ID, DISC_CD)
    -- FOREIGN KEY constraints removed
);

CREATE TABLE nimbus.USG_CDR (
    CDR_ID   BIGINT PRIMARY KEY,
    SUBSCR_ID VARCHAR,
    USG_TYP   VARCHAR CHECK (USG_TYP IN ('DATA','VOICE','SMS')),
    EVT_TS    TIMESTAMP,
    QTY       NUMERIC(12,4),
    RATED_FLG CHAR(1) CHECK (RATED_FLG IN ('Y','N'))
    -- FOREIGN KEY constraint removed
);

CREATE TABLE nimbus.RTD_EVT (
    RTD_ID     BIGINT PRIMARY KEY,
    CDR_ID     BIGINT,
    SUBSCR_ID  VARCHAR,
    BILL_PRD   CHAR(6) CHECK (BILL_PRD ~ '^[0-9]{6}$'), -- YYYYMM
    AMT        NUMERIC(12,2),
    INV_FLG    CHAR(1) CHECK (INV_FLG IN ('Y','N'))
    -- FOREIGN KEY constraints removed
);

CREATE TABLE nimbus.BILL_HDR (
    INV_NO        VARCHAR PRIMARY KEY,
    BILL_ACCT_NO VARCHAR,
    CUST_NO       VARCHAR,
    BILL_PRD      CHAR(6),
    INV_DT        DATE,
    TOT_AMT       NUMERIC(12,2),
    DUE_DT        DATE
    -- FOREIGN KEY constraints removed
);

CREATE TABLE nimbus.BILL_DTL (
    INV_NO    VARCHAR,
    LN_NO     INTEGER,
    SUBSCR_ID VARCHAR,
    CHG_TYP   VARCHAR CHECK (CHG_TYP IN ('RECUR','USAGE','DISC')),
    CHG_REF   VARCHAR NULL,
    AMT       NUMERIC(12,2),
    PRIMARY KEY (INV_NO, LN_NO)
    -- FOREIGN KEY constraints removed
);

CREATE TABLE nimbus.PYMT_TXN (
    PYMT_ID   VARCHAR PRIMARY KEY,
    CUST_NO   VARCHAR,
    REF_INV_NO VARCHAR NULL,
    PYMT_DT   DATE,
    PYMT_AMT  NUMERIC(12,2),
    CHNL      VARCHAR
    -- FOREIGN KEY constraint removed
);

CREATE TABLE nimbus.RENEW_LOG (
    RNW_ID   BIGINT PRIMARY KEY,
    CNTR_ID  BIGINT,
    DUE_DT   DATE,
    RNW_STAT VARCHAR CHECK (RNW_STAT IN ('DONE','FAILED','PENDING')),
    NEW_END_DT DATE NULL
    -- FOREIGN KEY constraint removed
);
